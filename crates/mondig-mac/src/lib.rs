/// Een rechthoek in de schermcoördinaten van macOS: in punten, met de oorsprong linksonder op
/// het hoofdscherm en `y` omhoog.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Kader {
    pub x: f64,
    pub y: f64,
    pub breedte: f64,
    pub hoogte: f64,
}

impl Kader {
    /// Ligt het punt erin, randen meegerekend?
    #[must_use]
    pub fn bevat(&self, punt: (f64, f64)) -> bool {
        let (x, y) = punt;
        x >= self.x && x <= self.x + self.breedte && y >= self.y && y <= self.y + self.hoogte
    }

    /// Het kwadraat van de afstand van het punt tot de rechthoek (0 als het erin ligt).
    fn afstand2(&self, punt: (f64, f64)) -> f64 {
        let (x, y) = punt;
        let dx = (self.x - x).max(0.0).max(x - (self.x + self.breedte));
        let dy = (self.y - y).max(0.0).max(y - (self.y + self.hoogte));
        dx * dx + dy * dy
    }
}

/// Het scherm waar je werkt. Net als op Windows eerst het scherm met het venster dat de focus
/// heeft (`voorkeur`, op de Mac `NSScreen.mainScreen`), anders het scherm onder de muis, en
/// anders het scherm het dichtst bij de muis. `None` zonder schermen.
#[must_use]
pub fn kies_scherm(voorkeur: Option<usize>, muis: (f64, f64), schermen: &[Kader]) -> Option<usize> {
    if let Some(index) = voorkeur.filter(|index| *index < schermen.len()) {
        return Some(index);
    }
    if let Some(index) = schermen.iter().position(|scherm| scherm.bevat(muis)) {
        return Some(index);
    }
    schermen
        .iter()
        .enumerate()
        .min_by(|(_, a), (_, b)| a.afstand2(muis).total_cmp(&b.afstand2(muis)))
        .map(|(index, _)| index)
}

/// Linksonder van de pil, in de coördinaten van macOS: horizontaal in het midden van het
/// werkgebied (`visibleFrame`, zonder menubalk en Dock), `marge` boven de onderrand of onder
/// de bovenrand. Is het werkgebied te smal, dan begint de pil op de linkerrand; onderaan blijft
/// de bovenkant binnen het werkgebied. Dezelfde regels als `pil::positie` op Windows, maar met
/// `y` omhoog.
#[must_use]
pub fn pil_oorsprong(werkgebied: Kader, maat: (f64, f64), boven: bool, marge: f64) -> (f64, f64) {
    let (breedte, hoogte) = maat;
    let x = werkgebied.x + ((werkgebied.breedte - breedte) / 2.0).max(0.0);
    let bovenrand = werkgebied.y + werkgebied.hoogte;
    let y = if boven {
        bovenrand - hoogte - marge
    } else {
        werkgebied.y + marge
    };
    // Te hoog voor het werkgebied: de bovenkant blijft zichtbaar.
    (x, y.min(bovenrand - hoogte))
}

#[cfg(test)]
