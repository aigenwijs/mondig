/// De bits van `CGEventFlags` voor ⇧, ⌃, ⌥ en ⌘ (`kCGEventFlagMask*` in `CGEventTypes.h`).
/// Caps Lock en Fn tellen niet: die zeggen niets over de sneltoets.
pub mod vlag {
    /// ⇧ (`kCGEventFlagMaskShift`).
    pub const SHIFT: u64 = 1 << 17;
    /// ⌃ (`kCGEventFlagMaskControl`).
    pub const CONTROL: u64 = 1 << 18;
    /// ⌥ (`kCGEventFlagMaskAlternate`).
    pub const OPTION: u64 = 1 << 19;
    /// ⌘ (`kCGEventFlagMaskCommand`).
    pub const COMMAND: u64 = 1 << 20;
    /// Caps Lock (`kCGEventFlagMaskAlphaShift`).
    pub const CAPS_LOCK: u64 = 1 << 16;
    /// Fn (`kCGEventFlagMaskSecondaryFn`).
    pub const FN: u64 = 1 << 23;
}

/// Is er in deze vlaggen een modifier van een sneltoets ingedrukt?
#[must_use]
pub fn modifier_in(vlaggen: u64) -> bool {
    vlaggen & (vlag::SHIFT | vlag::CONTROL | vlag::OPTION | vlag::COMMAND) != 0
}

