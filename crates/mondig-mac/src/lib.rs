    #[test]
    fn de_toets_voor_v_volgt_de_indeling() {
        // QWERTY: V zit op toetscode 9. Dvorak: daar geeft toetscode 47 een v.
        let qwerty = |toets| (toets == 9).then_some('v');
        let dvorak = |toets| match toets {
            9 => Some('k'),
            47 => Some('v'),
            _ => None,
        };
        assert_eq!(toets_voor_v(qwerty), Some(9));
        assert_eq!(toets_voor_v(dvorak), Some(47));
        // Geen indeling met een v (of geen gegevens): de aanroeper valt terug op 9.
        assert_eq!(toets_voor_v(|_| None), None);
    }

