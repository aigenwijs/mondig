/// Het type van platte tekst op het klembord (`NSPasteboardTypeString`).
pub const TEKST_TYPE: &str = "public.utf8-plain-text";

/// Markeringen die klembordbeheerders (Maccy, Paste, de geschiedenis van Raycast) vragen de
