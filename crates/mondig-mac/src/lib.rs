//! Mondig op de Mac, mijlpaal M1: dicteren in andere programma's.
//!
//! - [`klembord`] en [`invoer`]: de tekst als belofte op het klembord, buiten
//!   klembordbeheerders, ⌘V als toetsaanslag en het oude klembord terug na het leesbewijs.
//!   Lezen de programma's niet, dan typt Mondig in een tekstveld ([`focus`], [`is_tekstveld`]).
//!   De volgorde en de beslissingen staan in de app (`plakken/macos.rs`), tegen de trait
//!   [`Bord`]; [`klembord::Systeem`] is de echte uitvoering.
//! - [`rechten`]: het recht op toegankelijkheid (zonder dat recht houdt macOS de toetsaanslag
//!   tegen) en de knoppen naar Systeeminstellingen.
//! - [`pil`]: de pil tonen zonder dat Mondig actief wordt, boven andere vensters en op alle
//!   Spaces.
//! - [`geluid`] en [`wakker`]: het geluidje en de computer wakker houden tijdens het werk.
//!
//! De werkwijze volgt Handy (github.com/cjpais/Handy, MIT): `src-tauri/src/paste_tx/macos.rs`
//! voor plakken met een leesbewijs en `src-tauri/src/overlay.rs` voor de pil. Geen code
//! overgenomen, wel de aanpak.
//!
//! Op andere platforms bevat de crate alleen de gedeelde typen en de zuivere beslissingen, zodat
//! de app ze overal kan gebruiken en de tests overal draaien.

