/// Hooguit zoveel bytes van het oude klembord bewaren we (een enorme afbeelding uit een
/// fotoprogramma niet). Zelfde grens als op Windows.
pub const MAX_BEWAREN_BYTES: usize = 64 * 1024 * 1024;

/// Merkt de gebruiker het als dit type van het oude klembord niet terugkomt? Ja voor tekst,
/// opmaak, afbeeldingen, bestanden en adressen; nee voor de eigen typen van programma's,
/// want plakken werkt daarna gewoon met de tekst of de opmaak. De namen zijn de Uniform Type
/// Identifiers van Apple, plus de oude namen die oudere programma's nog zetten.
#[must_use]
pub fn merkbaar(soort: &str) -> bool {
    const MERKBAAR: [&str; 14] = [
        "public.utf8-plain-text",
        "public.utf16-plain-text",
        "public.plain-text",
        "public.rtf",
        "public.html",
        "com.apple.flat-rtfd",
        "public.png",
        "public.tiff",
        "public.jpeg",
        "com.adobe.pdf",
        "public.file-url",
        "public.url",
        "NSStringPboardType",
        "NSFilenamesPboardType",
    ];
    MERKBAAR.contains(&soort)
}

/// Telt een leesverzoek voor dit type als leesbewijs? Alleen de tekst zelf: een programma dat
/// naar de markeringen kijkt, is een klembordbeheerder, niet het doel van het plakken.
#[must_use]
pub fn telt_als_leesbewijs(soort: &str) -> bool {
    soort == TEKST_TYPE
}

/// Wat het programma vooraan is.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Voorgrond {
    /// Er is geen programma vooraan (zelden: alleen het bureaublad).
    Geen,
    /// Mondig zelf staat vooraan; de pil telt niet, die wordt nooit actief.
    Eigen,
    /// Een ander programma: daar plakken we in.
    Ander,
}

/// Wat er sinds het publiceren met de belofte gebeurde. De Objective-C-kant vult dit op de
/// hoofdthread, de app leest het op haar eigen thread.
#[derive(Debug, Default)]
pub struct Signalen {
    leesbewijzen: Mutex<Vec<Instant>>,
    eigendom_kwijt: AtomicBool,
    ingetrokken: AtomicBool,
}

impl Signalen {
    /// Een programma vroeg de tekst op.
    pub fn lees(&self, moment: Instant) {
        self.leesbewijzen
            .lock()
            .unwrap_or_else(PoisonError::into_inner)
            .push(moment);
    }

    /// Een ander programma nam het klembord over.
    pub fn verlies_eigendom(&self) {
        self.eigendom_kwijt.store(true, Ordering::SeqCst);
    }

    /// Mondig trok de belofte in om te typen: een leesverzoek dat nog binnenkomt, krijgt
    /// niets meer.
    pub fn trek_in(&self) {
        self.ingetrokken.store(true, Ordering::SeqCst);
    }

    /// Is de belofte ingetrokken?
    #[must_use]
    pub fn ingetrokken(&self) -> bool {
        self.ingetrokken.load(Ordering::SeqCst)
    }

    /// Alle leesbewijzen tot nu toe.
    #[must_use]
    pub fn leesbewijzen(&self) -> Vec<Instant> {
        self.leesbewijzen
            .lock()
            .unwrap_or_else(PoisonError::into_inner)
            .clone()
    }

    /// Nam een ander programma het klembord over?
    #[must_use]
    pub fn eigendom_kwijt(&self) -> bool {
        self.eigendom_kwijt.load(Ordering::SeqCst)
    }
}

/// Een kopie van het oude klembord: per item de typen met hun bytes, in de volgorde van het
/// klembord. Gewone Rust-gegevens, zodat de kopie tussen threads mag.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Kopie {
    /// De items, elk met `(type, bytes)`.
    pub items: Vec<Vec<(String, Vec<u8>)>>,
    /// Is alles bewaard wat de gebruiker zou missen (zie [`merkbaar`])?
    pub volledig: bool,
}

/// Wat de app van het systeem nodig heeft om te plakken. De echte uitvoering is
/// [`klembord::Systeem`]; de tests van de app gebruiken een nep-uitvoering, zodat de volgorde
/// ook op Windows getest wordt.
///
/// Elke methode mag vanaf elke thread aangeroepen worden. Wat op de hoofdthread moet, gaat daar
/// zelf heen (op de hoofdthread meteen, anders wachtend). Wie aanroept, mag dus nooit de
/// hoofdthread laten wachten op een slot dat hij zelf vasthoudt.
pub trait Bord: Send + Sync {
    /// Welk programma staat vooraan?
    fn voorgrond(&self) -> Voorgrond;
    /// Staat Mondig vooraan alleen omdat er op de pil geklikt is, dan het programma van
    /// daarvoor weer vooraan zetten. Geeft `true` als dat gebeurde.
    fn herstel_voorgrond(&self) -> bool;
    /// Mag Mondig toetsaanslagen sturen (het recht op toegankelijkheid)?
    fn toegankelijk(&self) -> bool;
    /// Staat beveiligde invoer aan? Dat geldt systeembreed: ook een programma op de
    /// achtergrond kan het aanzetten. Daarom alleen een mogelijke uitleg, nooit een reden om
    /// niet te plakken.
    fn beveiligde_invoer(&self) -> bool;
    /// Houdt de gebruiker nu ⌘, ⌥, ⌃ of ⇧ ingedrukt?
    fn modifier_ingedrukt(&self) -> bool;
    /// Zijn we op de hoofdthread? Daar mag niemand wachten op een slot van een plakactie.
    fn op_hoofdthread(&self) -> bool;
    /// Kopieert het klembord zoals het nu is, binnen `budget`.
    fn bewaar(&self, budget: Duration) -> Kopie;
    /// Zet `tekst` als belofte op het klembord, met de markeringen van [`VERBERG_TYPEN`].
    /// Geeft het nieuwe wijzigingsnummer, of `None` als het niet lukte. Vraagt een programma de
    /// tekst op, of neemt een ander het klembord over, dan komt dat in `signalen`.
    fn publiceer(&self, tekst: &str, signalen: Arc<Signalen>) -> Option<isize>;
    /// Stuurt ⌘V naar het programma vooraan. Blokkeert kort (⌘ blijft even ingedrukt). Geeft
    /// het moment waarop V verstuurd werd: pas lezingen vanaf dan tellen als leesbewijs. `None`
    /// als het niet lukte.
    fn stuur_cmd_v(&self) -> Option<Instant>;
    /// Zet een bewaard klembord terug, met een markering zodat het niet dubbel in een
    /// klembordgeschiedenis komt.
    fn zet_terug(&self, kopie: &Kopie) -> bool;
    /// Zet tekst blijvend op het klembord, met de markeringen.
    fn zet_tekst(&self, tekst: &str) -> bool;
    /// Rondt een plakactie af in één stap op de hoofdthread, zodat er niets tussen kan komen:
    /// is het klembord nog van deze plakactie (geen overname in `signalen` en nog wijzigingsnummer
    /// `nummer`), dan volgens `afsluiting` het oude klembord terug of de tekst erop. Anders
    /// alleen de eigen belofte loslaten; die van een nieuwere plakactie blijft staan.
    fn herstel(
        &self,
        signalen: &Arc<Signalen>,
        nummer: isize,
        afsluiting: Afsluiting,
        kopie: &Kopie,
        tekst: &str,
    ) -> Herstel;
    /// Het programma vooraan als procesnummer, om tijdens het typen te zien of de gebruiker
    /// van programma wisselde. `None` als er geen is.
    fn voorgrond_id(&self) -> Option<i32>;
    /// Heeft een bewerkbaar tekstveld de focus (zie [`is_tekstveld`])? `None` als het systeem
    /// het niet kon zeggen, bijvoorbeeld omdat het programma niet op tijd antwoordde.
    fn tekstveld(&self) -> Option<bool>;
    /// Trekt de belofte in voordat Mondig gaat typen, in één stap op de hoofdthread (daar komen
    /// ook de leesverzoeken binnen, dus er kan er geen tussen komen). Kwam er sinds `sinds`
    /// een lezing, dan gebeurt er niets ([`Intrekking::Gelezen`]). Is het klembord nog van deze
    /// plakactie (zoals bij [`Bord::herstel`]), dan wordt het leeg: een laat plakken krijgt
    /// niets, niet het dictaat en niet het oude klembord. Leesverzoeken die daarna nog
    /// binnenkomen, krijgen ook niets ([`Signalen::trek_in`]).
    fn trek_in(&self, signalen: &Arc<Signalen>, nummer: isize, sinds: Instant) -> Intrekking;
    /// Na het typen, in één stap op de hoofdthread: is het klembord nog zoals [`Bord::trek_in`]
    /// het achterliet (wijzigingsnummer `nummer`), dan de rest erop (`rest`), of anders het
    /// oude klembord terug. `None` als de gebruiker intussen zelf kopieerde: dat wint. Anders of
    /// het schrijven lukte.
    fn na_typen(&self, nummer: isize, kopie: &Kopie, rest: Option<&str>) -> Option<bool>;
    /// Typt tekst als Unicode-tekens in het programma vooraan, los van de toetsenbordindeling.
    /// Hooguit [`TYPBLOK`] UTF-16-eenheden per keer. `false` als het niet lukte.
    fn typ_tekst(&self, tekst: &str) -> bool;
}

/// Zoveel UTF-16-eenheden gaan er hooguit in één toetsgebeurtenis met
/// `CGEventKeyboardSetUnicodeString`. Apple noemt geen grens, maar langere reeksen worden
/// volgens ontwikkelaars afgekapt (gangbare bibliotheken blijven onder de twintig); kleine
/// blokken zijn veilig en kosten weinig tijd.
pub const TYPBLOK: usize = 16;

/// Wat [`Bord::trek_in`] deed.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Intrekking {
    /// De belofte is weg en het klembord is leeg, met dit nieuwe wijzigingsnummer.
    Ingetrokken {
        /// Het wijzigingsnummer van het lege klembord, voor [`Bord::na_typen`].
        nummer: isize,
    },
    /// Het doel las de tekst toch nog: niets aangeraakt, het telt als plakken.
    Gelezen,
    /// Het klembord was niet meer van deze plakactie: niets aangeraakt.
    NietVanOns,
}

/// Wat de toegankelijkheid van de Mac over het element met de focus zegt.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Focusveld {
    /// `AXRole`, bijvoorbeeld `AXTextField`.
    pub rol: Option<String>,
    /// `AXEditable`, als het programma dat geeft (webinhoud doet dat).
    pub bewerkbaar: Option<bool>,
    /// Heeft het een `AXSelectedTextRange`: een tekstcursor.
    pub selectie: bool,
}

/// De rollen van tekstvelden (`AXRoleConstants.h`).
const TEKSTROLLEN: [&str; 4] = ["AXTextField", "AXTextArea", "AXComboBox", "AXSearchField"];

/// Heeft een bewerkbaar tekstveld de focus? `AXEditable` beslist als het er is. Anders een
/// tekstrol, of een tekstcursor in iets dat geen hele webpagina is: een webpagina
/// (`AXWebArea`) als Gmail kan een selectie hebben zonder dat er iets te typen valt.
#[must_use]
pub fn is_tekstveld(veld: &Focusveld) -> bool {
    if let Some(bewerkbaar) = veld.bewerkbaar {
        return bewerkbaar;
    }
    match veld.rol.as_deref() {
        Some(rol) if TEKSTROLLEN.contains(&rol) => true,
        Some("AXWebArea") => false,
        _ => veld.selectie,
    }
}

/// Wat er bij het afronden met een klembord gebeurt dat nog van ons is.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Afsluiting {
    /// Het oude klembord terug (het doel las de tekst).
    Terugzetten,
    /// De tekst laten staan (geen leesbewijs: misschien kwam ⌘V niet aan).
    TekstLaten,
}

/// Wat [`Bord::herstel`] deed.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Herstel {
    /// Het klembord was niet meer van deze plakactie: niets aangeraakt.
    NietVanOns,
    /// Het oude klembord staat er weer.
    Teruggezet,
    /// De tekst staat erop (gevraagd, of omdat terugzetten mislukte).
    TekstGezet,
}

/// Zoekt de toets die in de huidige indeling `v` geeft: de eerste toetscode van 0 tot 127
/// waarvoor `vertaal` dat teken teruggeeft. Bij Dvorak is dat een andere toets dan bij
/// QWERTY. Zelfde aanpak als Handy (`src-tauri/src/input.rs`, MIT).
#[must_use]
pub fn toets_voor_v(mut vertaal: impl FnMut(u16) -> Option<char>) -> Option<u16> {
    (0..128).find(|&toets| vertaal(toets) == Some('v'))
}

